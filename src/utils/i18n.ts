export const translations: Record<Lang, Record<TranslationKey, string>> = { vi, en };

const STORAGE_KEY = 'benbi_lang_v1';

export function isLang(value: unknown): value is Lang {
  return value === 'vi' || value === 'en';
}

export function getStoredLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (isLang(stored)) return stored;
  } catch {
    // localStorage unavailable; fall back to Vietnamese.
  }
  return 'vi';
}

export function persistLang(lang: Lang): void {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Ignore private-mode storage failures; the in-memory choice still applies.
  }
}

export function localeOf(lang: Lang): string {
  return lang === 'vi' ? 'vi-VN' : 'en-US';
}

// Seeded before the first render so non-React modules (seeds, notifications) match the stored language.
let activeLang: Lang = getStoredLang();

export function setActiveLang(lang: Lang): void {
  activeLang = lang;
}

export function getActiveLang(): Lang {
  return activeLang;
}

export type TranslationVars = Record<string, string | number>;

export function translate(lang: Lang, key: TranslationKey, vars?: TranslationVars): string {
  const template = translations[lang][key] ?? translations.vi[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] === undefined ? match : String(vars[name]),
  );
}

/** Standalone translator for non-React modules; follows the active UI language. */
export function t(key: TranslationKey, vars?: TranslationVars): string {
  return translate(activeLang, key, vars);
}
